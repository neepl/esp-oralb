#!/usr/bin/env python3
"""tools/web/index.html -> include/web_page.h (gzip, byte array in flash). Run: python3 tools/gen_web.py"""
import gzip, pathlib, sys

root = pathlib.Path(__file__).resolve().parent.parent
src = (root / "tools/web/index.html").read_bytes()
gz = gzip.compress(src, 9, mtime=0)
rows = []
for i in range(0, len(gz), 16):
    rows.append("  " + ", ".join("0x%02x" % b for b in gz[i:i + 16]) + ",")
out = ("// Generated by tools/gen_web.py from tools/web/index.html (gzip). Do not edit.\n#pragma once\n#include <stddef.h>\n#include <stdint.h>\n\n"
       "static const size_t WEB_PAGE_GZ_LEN = %d;  // %d bytes before compression\nstatic const uint8_t WEB_PAGE_GZ[] = {\n%s\n};\n" % (len(gz), len(src), "\n".join(rows)))
(root / "include/web_page.h").write_text(out)
print("web_page.h: %d -> %d bytes" % (len(src), len(gz)), file=sys.stderr)
