#!/usr/bin/env python3
"""Generate lib/core/zone_model_data.h from tools/python/src/esp_oralb/zone_model.json (the "lda" model).

    uv run python tools/gen_model_header.py [model.json]

Emits the zone list (JSON order = firmware zone indices), feature standardisation (mean, scale),
LDA weights (zones x 12) and biases, plus the constants the feature extractor needs.
"""
import json
import sys
from pathlib import Path

root = Path(__file__).resolve().parents[1]
src = Path(sys.argv[1]) if len(sys.argv) > 1 else root / "tools/python/src/esp_oralb/zone_model.json"
m = json.loads(src.read_text())
if m.get("type") != "lda":
    sys.exit(f"{src}: expected an 'lda' model, got {m.get('type')!r}")
zones = m["zones"]
nf = len(m["mean"])
assert nf == 12 and len(m["scale"]) == nf and len(m["weights"]) == len(zones) == len(m["bias"])
assert all(len(w) == nf for w in m["weights"])


def vec(v):
    return ", ".join(repr(float(c)) for c in v)


weights = ",\n".join("    {%s}" % vec(w) for w in m["weights"])
out = f"""// GENERATED by tools/gen_model_header.py from {src.name} - do not edit.
// LDA zone model: score_z(x) = w_z . ((x - mean) / scale) + b_z on 12 window features.
#pragma once

namespace oralb {{

constexpr int ZONE_COUNT = {len(zones)};
constexpr int FEATURE_COUNT = {nf};
constexpr double ZONE_MODEL_WINDOW = {float(m['window'])!r};
constexpr double ZONE_MODEL_STAY = {float(m['stay'])!r};
constexpr double GYRO_RAD_S = {float(m['gyro_rad_s_per_unit'])!r};  // rad/s per raw gyro unit
constexpr double ACCEL_UNITS_PER_G = {float(m['accel_units_per_g'])!r};

constexpr const char* ZONE_CODES[ZONE_COUNT] = {{{", ".join('"%s"' % z for z in zones)}}};

constexpr double LDA_MEAN[FEATURE_COUNT] = {{{vec(m['mean'])}}};
constexpr double LDA_SCALE[FEATURE_COUNT] = {{{vec(m['scale'])}}};

constexpr double LDA_WEIGHTS[ZONE_COUNT][FEATURE_COUNT] = {{
{weights}
}};

constexpr double LDA_BIAS[ZONE_COUNT] = {{{vec(m['bias'])}}};

}}  // namespace oralb
"""
(root / "lib/core/zone_model_data.h").write_text(out)
print(f"wrote lib/core/zone_model_data.h ({len(zones)} zones, {nf} features)")
